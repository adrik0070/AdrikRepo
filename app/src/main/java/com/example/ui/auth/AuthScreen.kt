@Composable
private fun FestiveDiyaEmblem(modifier: Modifier = Modifier) {
    val flameOuterColor = MaterialTheme.colorScheme.secondaryContainer
    Canvas(modifier = modifier) {
        val w = size.width
        val h = size.height
        val center = Offset(w / 2f, h / 2f)

        // Outer decorative alpana rings
        drawCircle(
            color = HeroGoldAccent.copy(alpha = 0.20f),
            radius = w * 0.48f,
            center = center
        )
        drawCircle(
            color = HeroGoldAccent.copy(alpha = 0.55f),
            radius = w * 0.42f,
            center = center,
            style = Stroke(width = w * 0.025f)
        )

        // Diya flame outer
        val flameOuter = Path().apply {
            moveTo(w * 0.50f, h * 0.18f)
            cubicTo(w * 0.66f, h * 0.34f, w * 0.64f, h * 0.52f, w * 0.50f, h * 0.54f)
            cubicTo(w * 0.36f, h * 0.52f, w * 0.34f, h * 0.34f, w * 0.50f, h * 0.18f)
            close()
        }
        drawPath(path = flameOuter, color = HeroGoldAccent)

        // Diya flame inner core
        val flameInner = Path().apply {
            moveTo(w * 0.50f, h * 0.28f)
            cubicTo(w * 0.59f, h * 0.38f, w * 0.58f, h * 0.49f, w * 0.50f, h * 0.51f)
            cubicTo(w * 0.42f, h * 0.49f, w * 0.41f, h * 0.38f, w * 0.50f, h * 0.28f)
            close()
        }
        drawPath(path = flameInner, color = flameOuterColor)

        // Terracotta lamp bowl
        val bowlPath = Path().apply {
            moveTo(w * 0.24f, h * 0.56f)
            lineTo(w * 0.76f, h * 0.56f)
            cubicTo(w * 0.72f, h * 0.76f, w * 0.28f, h * 0.76f, w * 0.24f, h * 0.56f)
            close()
        }
        drawPath(path = bowlPath, color = HeroGoldAccent)
    }
}
